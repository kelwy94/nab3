import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../theme.dart';
import '../widgets/naba_widgets.dart';
import '../providers/auth_provider.dart';
import '../providers/job_provider.dart';
import '../models/types.dart';
import 'map_picker_screen.dart';
import 'package:latlong2/latlong.dart';

class RequestEquipmentScreen extends StatefulWidget {
  const RequestEquipmentScreen({super.key});

  @override
  State<RequestEquipmentScreen> createState() => _RequestEquipmentScreenState();
}

class _RequestEquipmentScreenState extends State<RequestEquipmentScreen> {
  String _selectedType = 'جرار';
  final List<String> _equipmentTypes = [
    'جرار',
    'لودر كبير',
    'لودر صغير',
    'سيارة ربع نقل',
    'سيارة جامبو',
    'حفار',
    'بلدوزر',
    'كلارك',
    'خباطة آبار',
    'بريمة آبار',
    'أخرى'
  ];

  final List<String> _tractorAttachments = [
    'مكبس',
    'دراسة',
    'قصابية',
    'ليذر',
    'محراث',
    'مقطورة',
    'كمبروسر'
  ];
  final List<String> _selectedAttachments = [];

  final _formKey = GlobalKey<FormState>();
  final _durationController = TextEditingController();
  final _addressController = TextEditingController();
  final _notesController = TextEditingController();
  final _priceController = TextEditingController();
  LatLng? _selectedLocation;
  bool _isSubmitting = false;

  void _submitRequest() async {
    if (!_formKey.currentState!.validate()) return;
    if (_selectedLocation == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
            content: Text('برجاء تحديد الموقع من الخريطة',
                textAlign: TextAlign.right)),
      );
      return;
    }

    setState(() => _isSubmitting = true);
    final user = Provider.of<AuthProvider>(context, listen: false).user;
    if (user == null) return;

    try {
      final jobProvider = Provider.of<JobProvider>(context, listen: false);

      String serviceDetails = _selectedType;
      if (_selectedType == 'جرار' && _selectedAttachments.isNotEmpty) {
        serviceDetails += ' (ملحقات: ${_selectedAttachments.join("، ")})';
      }

      final job = Job(
        id: '', // Generated by Firestore
        requesterUserId: user.id,
        type: 'equipment',
        serviceType: serviceDetails, // E.g: جرار (ملحقات: مكبس، دراسة)
        location: {
          'lat': _selectedLocation!.latitude,
          'lng': _selectedLocation!.longitude,
        },
        address: _addressController.text,
        startTime: DateTime.now().add(const Duration(hours: 1)),
        endTime: DateTime.now().add(const Duration(hours: 4)),
        status: JobStatus.requested,
        notes:
            "المدة/الكمية المطلوبة: ${_durationController.text} \nملاحظات المزارع: ${_notesController.text}",
        price: double.tryParse(_priceController
            .text), // Optional initial proposed price max budget
      );

      await jobProvider.addJob(job);

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
          content: Text('تم بث الطلب بنجاح لجميع أصحاب المعدات المتاحة!',
              textAlign: TextAlign.right),
          backgroundColor: Colors.green,
        ));
        Navigator.pop(context); // Go back to farmer dashboard
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
              content: Text('حدث خطأ أثناء بث الطلب: $e',
                  textAlign: TextAlign.right)),
        );
      }
    } finally {
      if (mounted) setState(() => _isSubmitting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
        backgroundColor: NabaTheme.background,
        appBar: const NabaAppBar(title: 'تأجير معدات زراعية'),
        body: Directionality(
            textDirection: TextDirection.rtl,
            child: Form(
                key: _formKey,
                child: SingleChildScrollView(
                  padding: const EdgeInsets.all(24),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.stretch,
                    children: [
                      const Text(
                        'طلب معدة بطريقة المزايدة المفتوحة',
                        style: TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 22,
                            color: NabaTheme.primary),
                      ),
                      const SizedBox(height: 8),
                      const Text(
                        'حدد نوع المعدة وتفاصيل المهمة. سيتم إرسال طلبك كإشعار لجميع أصحاب المعدات في المنطقة ليقدم كل منهم عرض سعر يمكنك التفاوض حوله والاختيار بينها.',
                        style: TextStyle(
                            color: Colors.grey, fontSize: 13, height: 1.5),
                      ),
                      const SizedBox(height: 24),
                      const Text('نوع المعدة المطلوبة',
                          style: TextStyle(fontWeight: FontWeight.bold)),
                      const SizedBox(height: 8),
                      Container(
                        padding: const EdgeInsets.symmetric(horizontal: 16),
                        decoration: BoxDecoration(
                          color: Colors.white,
                          borderRadius: BorderRadius.circular(16),
                          border: Border.all(color: Colors.grey.shade300),
                        ),
                        child: DropdownButtonHideUnderline(
                          child: DropdownButton<String>(
                            value: _selectedType,
                            isExpanded: true,
                            items: _equipmentTypes
                                .map((e) =>
                                    DropdownMenuItem(value: e, child: Text(e)))
                                .toList(),
                            onChanged: (v) {
                              setState(() {
                                _selectedType = v!;
                                if (_selectedType != 'جرار') {
                                  _selectedAttachments.clear();
                                }
                              });
                            },
                          ),
                        ),
                      ),
                      const SizedBox(height: 16),
                      if (_selectedType == 'جرار') ...[
                        const Text('الملحقات المطلوبة (اختياري)',
                            style: TextStyle(fontWeight: FontWeight.bold)),
                        const SizedBox(height: 8),
                        Wrap(
                          spacing: 8.0,
                          runSpacing: 4.0,
                          children: _tractorAttachments.map((attachment) {
                            final isSelected =
                                _selectedAttachments.contains(attachment);
                            return FilterChip(
                              label: Text(attachment,
                                  style: TextStyle(
                                      color: isSelected
                                          ? Colors.white
                                          : Colors.black87,
                                      fontSize: 13)),
                              selected: isSelected,
                              selectedColor: NabaTheme.primary,
                              onSelected: (selected) {
                                setState(() {
                                  if (selected) {
                                    _selectedAttachments.add(attachment);
                                  } else {
                                    _selectedAttachments.remove(attachment);
                                  }
                                });
                              },
                            );
                          }).toList(),
                        ),
                        const SizedBox(height: 16),
                      ],
                      if (_selectedType == 'سيارة جامبو') ...[
                        Container(
                          padding: const EdgeInsets.all(16),
                          margin: const EdgeInsets.only(bottom: 16),
                          decoration: BoxDecoration(
                            color: Colors.blue.shade50,
                            borderRadius: BorderRadius.circular(16),
                            border: Border.all(color: Colors.blue.shade200),
                          ),
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Row(
                                children: [
                                  Icon(Icons.info_outline_rounded,
                                      color: Colors.blue.shade700),
                                  const SizedBox(width: 8),
                                  Text('أسعار الفرافرة الاسترشادية للجامبو:',
                                      style: TextStyle(
                                          fontWeight: FontWeight.bold,
                                          color: Colors.blue.shade700)),
                                ],
                              ),
                              const SizedBox(height: 8),
                              const Text(
                                  '• الفرافرة (المدينة): 2000 ج.م\n• الكفاح / أبو منقار: 2500 - 3000 ج.م\n• سهل بركة: 3500 - 4500 ج.م',
                                  style: TextStyle(height: 1.5, fontSize: 13)),
                            ],
                          ),
                        ),
                      ],
                      const Text('تحديد موقع العمل',
                          style: TextStyle(fontWeight: FontWeight.bold)),
                      const SizedBox(height: 8),
                      InkWell(
                        onTap: () async {
                          final latLng = await Navigator.push<LatLng>(
                              context,
                              MaterialPageRoute(
                                  builder: (_) => const MapPickerScreen()));
                          if (latLng != null) {
                            setState(() => _selectedLocation = latLng);
                          }
                        },
                        child: Container(
                          height: 56,
                          padding: const EdgeInsets.symmetric(horizontal: 16),
                          decoration: BoxDecoration(
                            color: Colors.white,
                            border: Border.all(color: Colors.grey.shade300),
                            borderRadius: BorderRadius.circular(16),
                          ),
                          child: Row(
                            children: [
                              const Icon(Icons.location_on,
                                  color: NabaTheme.primary),
                              const SizedBox(width: 12),
                              Text(
                                  _selectedLocation == null
                                      ? 'اضغط لتحديد الموقع على الخريطة'
                                      : 'تم تحديد الموقع بنجاح',
                                  style: TextStyle(
                                      color: _selectedLocation == null
                                          ? Colors.grey
                                          : Colors.black,
                                      fontWeight: FontWeight.bold)),
                            ],
                          ),
                        ),
                      ),
                      const SizedBox(height: 16),
                      _buildTextField('عنوان تقريبي مكمل (قرية/علامة مميزة)',
                          _addressController,
                          isRequired: true),
                      const SizedBox(height: 16),
                      _buildTextField(
                          'مدة العمل (أو كام فدان/ساعة)', _durationController,
                          isRequired: true),
                      const SizedBox(height: 16),
                      _buildTextField('السعر المبدئي المقترح (ج.م) [اختياري]',
                          _priceController,
                          isRequired: false, isNumber: true),
                      const SizedBox(height: 16),
                      _buildTextField(
                          'ملاحظات إضافية للطالب (اختياري)', _notesController,
                          isRequired: false, maxLines: 3),
                      const SizedBox(height: 32),
                      SizedBox(
                        height: 56,
                        child: ElevatedButton(
                          onPressed: _isSubmitting ? null : _submitRequest,
                          style: ElevatedButton.styleFrom(
                            backgroundColor: NabaTheme.primary,
                            shape: RoundedRectangleBorder(
                                borderRadius: BorderRadius.circular(16)),
                          ),
                          child: _isSubmitting
                              ? const CircularProgressIndicator(
                                  color: Colors.white)
                              : const Text('بث الطلب لأصحاب المعدات',
                                  style: TextStyle(
                                      color: Colors.white,
                                      fontWeight: FontWeight.bold,
                                      fontSize: 18)),
                        ),
                      )
                    ],
                  ),
                ))));
  }

  Widget _buildTextField(String label, TextEditingController controller,
      {bool isRequired = false, bool isNumber = false, int maxLines = 1}) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(label, style: const TextStyle(fontWeight: FontWeight.bold)),
        const SizedBox(height: 8),
        TextFormField(
          controller: controller,
          keyboardType: isNumber ? TextInputType.number : TextInputType.text,
          maxLines: maxLines,
          validator:
              isRequired ? (v) => v!.isEmpty ? 'هذا الحقل مطلوب' : null : null,
          decoration: InputDecoration(
            filled: true,
            fillColor: Colors.white,
            border: OutlineInputBorder(
              borderRadius: BorderRadius.circular(16),
              borderSide: BorderSide(color: Colors.grey.shade300),
            ),
            enabledBorder: OutlineInputBorder(
              borderRadius: BorderRadius.circular(16),
              borderSide: BorderSide(color: Colors.grey.shade300),
            ),
          ),
        ),
      ],
    );
  }
}
